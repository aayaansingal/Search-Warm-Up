// Regenerates the list of Google search domains the extension supports.
//
// Usage: node scripts/update-google-domains.mjs
//
// Fetches Google's official list (https://www.google.com/supported_domains),
// then rewrites src/google-domains.js plus the content-script matches and
// host permissions in manifest.json. Chrome match patterns cannot wildcard a top-level domain,
// so every domain has to be listed explicitly.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const SUPPORTED_DOMAINS_URL = "https://www.google.com/supported_domains";
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(projectRoot, "manifest.json");
const domainsModulePath = path.join(projectRoot, "src", "google-domains.js");

async function fetchGoogleDomains() {
  const response = await fetch(SUPPORTED_DOMAINS_URL);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${SUPPORTED_DOMAINS_URL}: HTTP ${response.status}`);
  }
  const text = await response.text();

  // Each line looks like ".google.co.uk"; turn it into "www.google.co.uk".
  const domains = text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => /^\.google\.[a-z.]+$/.test(line))
    .map((line) => `www${line}`);

  if (domains.length === 0) {
    throw new Error("The fetched domain list was empty; refusing to overwrite files.");
  }
  return [...new Set(domains)];
}

async function writeDomainsModule(domains) {
  const lines = domains.map((domain) => `  "${domain}",`).join("\n");
  const source =
    "// Generated by scripts/update-google-domains.mjs; do not edit by hand.\n" +
    "// Source: " + SUPPORTED_DOMAINS_URL + "\n\n" +
    "export const GOOGLE_DOMAINS = [\n" + lines + "\n];\n";
  await writeFile(domainsModulePath, source);
}

// Hosts that serve Google's CAPTCHA ("sorry") page besides the search domains.
// Keep in sync with EXTRA_CAPTCHA_HOSTS in src/background.js.
const EXTRA_CAPTCHA_HOSTS = ["ipv4.google.com", "ipv6.google.com"];

async function updateManifest(domains) {
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  const searchPatterns = domains.map((domain) => `https://${domain}/search*`);

  // The content script only runs on results pages.
  manifest.content_scripts[0].matches = searchPatterns;

  // Host access lets the background see when a mid-warm-up tab is on a results
  // page or a CAPTCHA page; any other site's URL stays hidden from it, which is
  // exactly how it recognises that the user has left the sequence.
  const captchaHosts = [...domains, ...EXTRA_CAPTCHA_HOSTS];
  const captchaPatterns = captchaHosts.map((host) => `https://${host}/sorry/*`);
  manifest.host_permissions = [...searchPatterns, ...captchaPatterns];

  await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
}

const domains = await fetchGoogleDomains();
await writeDomainsModule(domains);
await updateManifest(domains);
console.log(`Wrote ${domains.length} Google domains.`);
